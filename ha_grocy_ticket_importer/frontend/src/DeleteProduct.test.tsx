import { act, screen, waitFor } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { beforeEach, expect, it, vi } from "vitest";
import * as api from "./api";
import { DeleteProduct } from "./DeleteProduct";
import { deferred, renderWithClient } from "./test/helpers";
vi.mock("./api", async original => ({ ...(await original<typeof api>()), getProductDeletion: vi.fn(), deleteProduct: vi.fn() }));
const preview = { product_id: 7, name: "Sin uso", allowed: true, blockers: [], history_count: 4, stock_amount: "2", token: "a".repeat(64), barcode_count: 1, conversion_count: 0 };
beforeEach(() => { vi.resetAllMocks(); vi.mocked(api.getProductDeletion).mockResolvedValue(preview); });
it("uses a Yes/No modal with no typed confirmation and dispatches once", async () => {
  const pending = deferred<unknown>();
  vi.mocked(api.deleteProduct).mockReturnValue(pending.promise);
  const onDeleted = vi.fn();
  renderWithClient(<DeleteProduct id={7} onDeleted={onDeleted} />);
  await userEvent.click(screen.getByRole("button", { name: "Eliminar producto" }));
  await screen.findByText("Existencias: 2. Movimientos: 4.");
  expect(screen.queryByRole("textbox")).toBeNull();
  expect(screen.queryByRole("checkbox")).toBeNull();
  await userEvent.click(screen.getByRole("button", { name: "No" }));
  expect(api.deleteProduct).not.toHaveBeenCalled();
  await userEvent.click(screen.getByRole("button", { name: "Eliminar producto" }));
  await waitFor(() => expect(screen.getByRole("button", { name: "Sí" })).toHaveProperty("disabled", false));
  await userEvent.dblClick(screen.getByRole("button", { name: "Sí" }));
  expect(api.deleteProduct).toHaveBeenCalledExactlyOnceWith(7, "Sin uso", preview.token, expect.any(String));
  await act(async () => pending.resolve({ deleted: true }));
  await waitFor(() => expect(onDeleted).toHaveBeenCalledOnce());
});
it("blocks dependencies and an uncertain deletion cannot be resubmitted", async () => {
  vi.mocked(api.getProductDeletion).mockResolvedValueOnce({ ...preview, allowed: false, blockers: ["alias de Alexa"] });
  vi.mocked(api.deleteProduct).mockRejectedValue(new Error("Resultado incierto"));
  renderWithClient(<DeleteProduct id={7} onDeleted={vi.fn()} />);
  await userEvent.click(screen.getByRole("button", { name: "Eliminar producto" }));
  await screen.findByText("alias de Alexa");
  expect(screen.getByRole("button", { name: "Sí" })).toHaveProperty("disabled", true);
  await userEvent.click(screen.getByRole("button", { name: "No" }));
  await userEvent.click(screen.getByRole("button", { name: "Eliminar producto" }));
  await waitFor(() => expect(screen.getByRole("button", { name: "Sí" })).toHaveProperty("disabled", false));
  await userEvent.click(screen.getByRole("button", { name: "Sí" }));
  await screen.findByText(/Resultado incierto/);
  expect(screen.getByRole("button", { name: "Sí" })).toHaveProperty("disabled", true);
  expect(api.deleteProduct).toHaveBeenCalledOnce();
});
