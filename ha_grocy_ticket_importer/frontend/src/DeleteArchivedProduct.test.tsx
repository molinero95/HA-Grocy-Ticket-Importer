import { act, screen, waitFor } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { beforeEach, expect, it, vi } from "vitest";
import * as api from "./api";
import { DeleteArchivedProduct } from "./DeleteArchivedProduct";
import { deferred, renderWithClient } from "./test/helpers";
vi.mock("./api", async (original) => ({ ...(await original<typeof api>()), getProductDeletion: vi.fn(), deleteArchivedProduct: vi.fn() }));
const preview = { product_id: 7, name: "Sin uso", allowed: true, blockers: [], token: "a".repeat(64), barcode_count: 1, conversion_count: 0 };
beforeEach(() => { vi.resetAllMocks(); vi.mocked(api.getProductDeletion).mockResolvedValue(preview); });
it("requires a fresh review and the exact name before one deletion, then clears the archived cache", async () => {
  const pending = deferred<unknown>();
  vi.mocked(api.deleteArchivedProduct).mockReturnValue(pending.promise);
  const onDeleted = vi.fn();
  const { client } = renderWithClient(<DeleteArchivedProduct id={7} onDeleted={onDeleted} />);
  client.setQueryDefaults(["archived"], { gcTime: Infinity });
  client.setQueryData(["archived"], { items: [{ id: 7 }] });
  expect(api.getProductDeletion).not.toHaveBeenCalled();
  await userEvent.click(screen.getByRole("button", { name: "Revisar eliminación" }));
  const confirm = await screen.findByRole("button", { name: "Eliminar producto definitivamente" });
  expect(confirm).toHaveProperty("disabled", true);
  const input = screen.getByRole("textbox", { name: "Escribe «Sin uso» para confirmar" });
  await userEvent.type(input, "sin uso");
  expect(confirm).toHaveProperty("disabled", true);
  await userEvent.clear(input); await userEvent.type(input, "Sin uso");
  await userEvent.dblClick(confirm);
  expect(api.deleteArchivedProduct).toHaveBeenCalledExactlyOnceWith(7, "Sin uso", "Sin uso", preview.token, expect.any(String));
  await act(async () => pending.resolve({ deleted: true, product_id: 7 }));
  await waitFor(() => expect(onDeleted).toHaveBeenCalledOnce());
  expect(client.getQueryState(["archived"])?.isInvalidated).toBe(true);
});
it("shows history blockers without a confirmation form or write", async () => {
  vi.mocked(api.getProductDeletion).mockResolvedValue({ ...preview, allowed: false, blockers: ["historial de movimientos", "alias de Alexa"] });
  renderWithClient(<DeleteArchivedProduct id={7} onDeleted={vi.fn()} />);
  await userEvent.click(screen.getByRole("button", { name: "Revisar eliminación" }));
  expect((await screen.findByRole("alert")).textContent).toContain("historial de movimientos");
  expect(screen.queryByRole("textbox")).toBeNull();
  expect(api.deleteArchivedProduct).not.toHaveBeenCalled();
});
it("requires another read after a failed audit and never substitutes an empty preview", async () => {
  vi.mocked(api.getProductDeletion).mockRejectedValueOnce(new Error("No se pudo verificar"));
  renderWithClient(<DeleteArchivedProduct id={7} onDeleted={vi.fn()} />);
  await userEvent.click(screen.getByRole("button", { name: "Revisar eliminación" }));
  await userEvent.click(await screen.findByRole("button", { name: "Reintentar revisión" }));
  await screen.findByRole("textbox");
  expect(api.getProductDeletion).toHaveBeenCalledTimes(2);
  expect(api.deleteArchivedProduct).not.toHaveBeenCalled();
});
it("locks an uncertain deletion against retry within the sheet", async () => {
  vi.mocked(api.deleteArchivedProduct).mockRejectedValue(new Error("Resultado incierto"));
  const onDeleted = vi.fn();
  renderWithClient(<DeleteArchivedProduct id={7} onDeleted={onDeleted} />);
  await userEvent.click(screen.getByRole("button", { name: "Revisar eliminación" }));
  await userEvent.type(await screen.findByRole("textbox"), "Sin uso");
  await userEvent.click(screen.getByRole("button", { name: "Eliminar producto definitivamente" }));
  await screen.findByRole("alert");
  expect(screen.getByRole("button", { name: "Eliminar producto definitivamente" })).toHaveProperty("disabled", true);
  await userEvent.click(screen.getByRole("button", { name: "Cerrar revisión" }));
  expect(screen.getByRole("button", { name: "Revisar eliminación" })).toHaveProperty("disabled", true);
  expect(api.deleteArchivedProduct).toHaveBeenCalledOnce();
  expect(onDeleted).not.toHaveBeenCalled();
});
