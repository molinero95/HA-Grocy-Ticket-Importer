import { act, screen, waitFor } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { beforeEach, expect, it, vi } from "vitest";
import { ShoppingProductCreation } from "./ShoppingProductCreation";
import * as api from "./api";
import { deferred, renderWithClient } from "./test/helpers";
vi.mock("./api", async original => ({ ...(await original<typeof api>()), getShoppingCreationContext: vi.fn(), getCatalogUnits: vi.fn(), createShoppingProduct: vi.fn(), chooseAlexaMatch: vi.fn(), lookupPhoto: vi.fn() }));
const context: api.ShoppingCreationContext = {key: "gel alexa", name: "Gel Alexa", generation: 1, can_create: true, product_id: null, product_name: null, can_associate: false, associated: false};
beforeEach(() => {
  vi.resetAllMocks();
  vi.mocked(api.getShoppingCreationContext).mockResolvedValue(context);
  vi.mocked(api.getCatalogUnits).mockResolvedValue([{id: 2, name: "Piece"}]);
  vi.mocked(api.lookupPhoto).mockResolvedValue({photo: null});
});
it("prefills an Alexa name, creates without stock once and closes after automatic association", async () => {
  const pending = deferred<api.ShoppingCreationResult>();
  vi.mocked(api.createShoppingProduct).mockReturnValue(pending.promise);
  const saved = vi.fn();
  renderWithClient(<ShoppingProductCreation sourceKey="gel alexa" name="Gel Alexa" onClose={vi.fn()} onSaved={saved} />);
  const name = await screen.findByLabelText("Nombre", {exact: true});
  expect(name).toHaveProperty("value", "Gel Alexa");
  expect(screen.queryByLabelText("Stock inicial")).toBeNull();
  await userEvent.clear(name); await userEvent.type(name, "Jabón neutro");
  await screen.findByRole("option", {name: "Piece"});
  await userEvent.selectOptions(screen.getByLabelText("Unidad", {exact: true}), "2");
  await userEvent.dblClick(screen.getByRole("button", {name: "Guardar producto"}));
  expect(api.createShoppingProduct).toHaveBeenCalledExactlyOnceWith("gel alexa", context, {name: "Jabón neutro", barcode: "", unit_id: 2, initial_stock: "0", pack_size: "1"}, expect.any(String));
  await act(async () => pending.resolve({created: true, product_id: 8, associated: true}));
  await waitFor(() => expect(saved).toHaveBeenCalledOnce());
  expect(api.chooseAlexaMatch).not.toHaveBeenCalled();
});
it("asks before reusing an existing product and never calls creation again", async () => {
  const prepared = {...context, can_create: false, product_id: 7, product_name: "Producto existente", can_associate: true};
  vi.mocked(api.getShoppingCreationContext).mockResolvedValueOnce(context).mockResolvedValue(prepared);
  vi.mocked(api.createShoppingProduct).mockResolvedValue({created: false, product_id: 7, associated: false});
  const saved = vi.fn();
  renderWithClient(<ShoppingProductCreation sourceKey="gel alexa" name="Gel Alexa" onClose={vi.fn()} onSaved={saved} />);
  await screen.findByRole("option", {name: "Piece"});
  await userEvent.selectOptions(await screen.findByLabelText("Unidad", {exact: true}), "2");
  await userEvent.click(screen.getByRole("button", {name: "Guardar producto"}));
  const associate = await screen.findByRole("button", {name: "Asociar este producto"});
  await waitFor(() => expect(associate).toHaveProperty("disabled", false));
  expect(api.chooseAlexaMatch).not.toHaveBeenCalled();
  await userEvent.click(associate);
  await waitFor(() => expect(saved).toHaveBeenCalledOnce());
  expect(api.chooseAlexaMatch).toHaveBeenCalledExactlyOnceWith("gel alexa", 7, expect.any(String));
  expect(api.createShoppingProduct).toHaveBeenCalledOnce();
});
it("locks an uncertain creation and keeps its entered values for checking", async () => {
  vi.mocked(api.createShoppingProduct).mockRejectedValue(new Error("Comprueba el catálogo y la lista"));
  renderWithClient(<ShoppingProductCreation sourceKey="gel alexa" name="Gel Alexa" onClose={vi.fn()} onSaved={vi.fn()} />);
  await screen.findByRole("option", {name: "Piece"});
  await userEvent.selectOptions(await screen.findByLabelText("Unidad", {exact: true}), "2");
  await userEvent.click(screen.getByRole("button", {name: "Guardar producto"}));
  await screen.findByRole("alert");
  expect(screen.getByRole("button", {name: "Guardar producto"})).toHaveProperty("disabled", true);
  expect(screen.getByLabelText("Nombre", {exact: true})).toHaveProperty("value", "Gel Alexa");
  expect(api.createShoppingProduct).toHaveBeenCalledOnce();
});
